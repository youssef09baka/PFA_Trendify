const { generateAnalysis } = require("../services/aiService");

const {
  evaluateTrend,
} = require("../services/aiEvaluatorService");

const {
  verifyCredibility,
} = require("../services/credibilityService");

const {
  getRealTrends,
} = require("../services/data");

const getTrends = async (req, res) => {

  try {

    let trends = await getRealTrends();

    for (let trend of trends) {

      // 🔥 AI evaluation
      const evaluation =
        await evaluateTrend(trend);

      // 🔥 credibility verification
      const credibilityData =
        await verifyCredibility(trend);

      trend.verifiedSources =
        credibilityData.verifiedSources;

      trend.isFakeNews =
        credibilityData.isFakeNews;

      trend.warning =
        credibilityData.warning;

      trend.relevance =
        evaluation.relevance;

      trend.credibility = Math.max(
        evaluation.credibility,
        credibilityData.credibilityScore
      );

      trend.businessPotential =
        evaluation.businessPotential;

      // 🔥 intelligent AI score
      trend.score = Math.floor(

        trend.popularity * 0.3 +

        trend.growth * 0.2 +

        trend.relevance * 0.2 +

        trend.credibility * 0.15 +

        trend.businessPotential * 0.15
      );

      // 🔥 AI analysis
      trend.analysis =
        await generateAnalysis(trend);

      trend.idea =
        "Generated by AI";
    }

    // 🔥 sort by score
    trends.sort(
      (a, b) => b.score - a.score
    );

    return res.json({
      trends,
    });

  } catch (error) {

    console.error(error);

    return res.status(500).json({
      error: "Failed to get trends",
    });
  }
};

module.exports = {
  getTrends,
};