const test1_SlugGeneration = async () => {
  console.log('\n' + '='.repeat(70));
  console.log('TEST 1: Missing slug field in trend persistence');
  console.log('='.repeat(70));

  try {
    // Test data WITHOUT slug field
    const trendWithoutSlug = {
      title: 'Test Trend AI Analysis',
      source: 'Reddit',
      popularity: 100,
      growth: 25,
      num_comments: 50,
      post_length: 200,
      hour: 12,
      title_length: 26,
      sentiment: 0.5,
    };

    log('SLUG', 'Created trend object WITHOUT slug field', { ...trendWithoutSlug, slug: 'UNDEFINED' });

    // Call saveTrends - this should generate slug
    log('SLUG', 'Calling saveTrends()...');
    const saved = await saveTrends([trendWithoutSlug]);

    if (!saved || saved.length === 0) {
      log('SLUG', '❌ FAILED: saveTrends returned empty array');
      TESTS.slug = 'REAL_BUG: saveTrends returned no results';
      return;
    }

    const savedTrend = saved[0];

    if (!savedTrend.slug) {
      log('SLUG', '❌ FAILED: Saved trend has NO slug field', { slug: savedTrend.slug });
      TESTS.slug = 'REAL_BUG: slug field not generated by saveTrends';
      return;
    }

    // Verify in database
    const dbTrend = await Trend.findById(savedTrend._id).lean();
    if (!dbTrend.slug) {
      log('SLUG', '❌ FAILED: Database trend has NO slug field', { slug: dbTrend.slug });
      TESTS.slug = 'REAL_BUG: slug not persisted in database';
      return;
    }

    log('SLUG', '✅ SUCCESS: Slug was generated and persisted', {
      generatedSlug: savedTrend.slug,
      dbSlug: dbTrend.slug,
      match: savedTrend.slug === dbTrend.slug,
    });
    TESTS.slug = 'FALSE_POSITIVE: slug field IS generated by saveTrends';

  } catch (error) {
    log('SLUG', '❌ EXCEPTION:', { error: error.message, code: error.code });
    TESTS.slug = `REAL_BUG: saveTrends throws ${error.message}`;
  }
};

const test2_AIQuotaRaceCondition = async () => {
  console.log('\n' + '='.repeat(70));
  console.log('TEST 2: AI Quota Race Condition');
  console.log('='.repeat(70));

  try {
    // Create test user with 5 analyses left
    let testUser = await User.findOne({ email: 'quota-test@example.com' });
    if (!testUser) {
      const bcrypt = require('bcryptjs');
      const salt = await bcrypt.genSalt(10);
      const hashed = await bcrypt.hash('TestPassword123', salt);
      testUser = await User.create({
        name: 'Quota Test User',
        email: 'quota-test@example.com',
        password: hashed,
        aiRemaining: 5,
        aiLastReset: new Date(),
      });
      log('QUOTA', 'Created test user', { id: testUser._id, aiRemaining: testUser.aiRemaining });
    } else {
      testUser.aiRemaining = 5;
      await testUser.save();
      log('QUOTA', 'Reset test user quota', { aiRemaining: testUser.aiRemaining });
    }

    // Simulate concurrent quota decrements
    // This mimics 5 simultaneous requests all decrementing the same quota
    log('QUOTA', 'Simulating 5 concurrent quota decrements...');

    const decrementTasks = [];
    for (let i = 0; i < 5; i++) {
      decrementTasks.push(
        (async () => {
          const user = await User.findById(testUser._id);
          const before = user.aiRemaining;
          
          // Simulate the analyzeTrend logic:
          // 1. Check quota
          if (user.aiRemaining <= 0) {
            return { before, after: user.aiRemaining, result: 'REJECTED' };
          }
          
          // 2. Simulate async operation (generateTrendAnalysis)
          await new Promise(r => setTimeout(r, 10));
          
          // 3. Decrement quota (the race happens here)
          user.aiRemaining = Math.max(0, (user.aiRemaining || 0) - 1);
          await user.save();
          
          return { before, after: user.aiRemaining, result: 'SUCCESS' };
        })()
      );
    }

    const results = await Promise.all(decrementTasks);

    log('QUOTA', 'Concurrent decrement results:', { results });

    // Fetch final state from database
    const finalUser = await User.findById(testUser._id);
    const expectedRemaining = 0; // 5 - 5 = 0
    const actualRemaining = finalUser.aiRemaining;

    log('QUOTA', 'Final state check', {
      expected: expectedRemaining,
      actual: actualRemaining,
      isCorrect: actualRemaining === expectedRemaining,
    });

    if (actualRemaining < 0) {
      log('QUOTA', '❌ REAL_BUG: Quota went NEGATIVE (race condition confirmed)', { actual: actualRemaining });
      TESTS.aiQuota = 'REAL_BUG: Quota can go negative due to race condition';
    } else if (actualRemaining > expectedRemaining) {
      log('QUOTA', '⚠️ PARTIAL_BUG: Some decrements were lost', { expected: expectedRemaining, actual: actualRemaining });
      TESTS.aiQuota = 'REAL_BUG: Some quota decrements were lost due to concurrency';
    } else {
      log('QUOTA', '✅ PASS: Quota handled correctly', { actual: actualRemaining });
      TESTS.aiQuota = 'FALSE_POSITIVE: Quota race condition not reproducible in this test';
    }

  } catch (error) {
    log('QUOTA', '❌ EXCEPTION:', { error: error.message });
    TESTS.aiQuota = `REAL_BUG: ${error.message}`;
  }
};

const test3_ObjectIdValidation = async () => {
  console.log('\n' + '='.repeat(70));
  console.log('TEST 3: ObjectId Validation on Trend Detail');
  console.log('='.repeat(70));

  try {
    const { Types } = require('mongoose');

    // Test invalid ObjectID formats
    const invalidIds = [
      'not-a-valid-id',
      '12345',
      'xxxxxxxxxxxxxxxxxxxxxxxx',
      '000',
      '',
    ];

    log('OBJECTID', 'Testing invalid ObjectId formats...');

    for (const id of invalidIds) {
      const isValid = Types.ObjectId.isValid(id);
      log('OBJECTID', `ID: "${id}" - Valid: ${isValid}`);

      if (isValid) {
        // Try querying with this invalid ID
        try {
          const trend = await Trend.findById(id).lean();
          log('OBJECTID', `  Query result: ${trend ? 'Found' : 'Not found'}`);
        } catch (queryErr) {
          log('OBJECTID', `  Query error: ${queryErr.message}`);
        }
      }
    }

    log('OBJECTID', 'Summary: getTrendDetail controller checks ObjectId validity?');
    const fs = require('fs');
    const feedControllerPath = './controllers/feedController.js';
    const content = fs.readFileSync(feedControllerPath, 'utf8');
    
    const hasObjectIdValidation = content.includes('Types.ObjectId.isValid') || content.includes('ObjectId.isValid');
    const hasValidation = content.includes('if (!id');
    
    if (!hasObjectIdValidation && !hasValidation) {
      log('OBJECTID', '❌ REAL_BUG: No ObjectId validation found in getTrendDetail', { hasValidation });
      TESTS.objectId = 'REAL_BUG: getTrendDetail does not validate ObjectId format';
    } else {
      log('OBJECTID', '✅ or ⚠️: Some validation present', { hasObjectIdValidation, hasValidation });
      TESTS.objectId = 'FALSE_POSITIVE or NEEDS_VERIFICATION: Validation logic exists but behavior unclear';
    }

  } catch (error) {
    log('OBJECTID', '❌ EXCEPTION:', { error: error.message });
    TESTS.objectId = `REAL_BUG: ${error.message}`;
  }
};

